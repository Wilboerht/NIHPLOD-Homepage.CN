"use client";

/**
 * 社交分享悬浮球组件
 * 紧贴页面右侧，hover 展开分享选项
 */

import { useState, useCallback, useEffect } from "react";
import { m, AnimatePresence } from "framer-motion";
import { Share2, Loader2, Download, Check } from "lucide-react";
import { cn } from "@/lib/utils";

/** 分享选项配置 */
export interface ShareOption {
  key: string;
  label: string;
  icon: React.ReactNode;
  bgColor: string;
  onClick: () => void;
}

interface ShareFloatingButtonProps {
  /** 分享选项列表 */
  options: ShareOption[];
  /** 保存图片回调 */
  onSaveImage?: () => Promise<void>;
  /** 是否正在生成图片 */
  isGeneratingImage?: boolean;
  /** 是否显示保存按钮 */
  showSaveButton?: boolean;
  /** 复制成功状态 */
  copied?: boolean;
  /** 自定义类名 */
  className?: string;
}

export function ShareFloatingButton({
  options,
  onSaveImage,
  isGeneratingImage = false,
  showSaveButton = true,
  copied = false,
  className,
}: ShareFloatingButtonProps) {
  const [isExpanded, setIsExpanded] = useState(false);
  const [isMobile, setIsMobile] = useState(false);

  // 检测移动端
  useEffect(() => {
    const checkMobile = () => {
      setIsMobile(window.innerWidth < 768);
    };
    checkMobile();
    window.addEventListener("resize", checkMobile);
    return () => window.removeEventListener("resize", checkMobile);
  }, []);

  const handleMouseEnter = useCallback(() => {
    if (!isMobile) {
      setIsExpanded(true);
    }
  }, [isMobile]);

  const handleMouseLeave = useCallback(() => {
    if (!isMobile) {
      setIsExpanded(false);
    }
  }, [isMobile]);

  const handleClick = useCallback(() => {
    if (isMobile) {
      setIsExpanded((prev) => !prev);
    }
  }, [isMobile]);

  const handleOptionClick = useCallback((option: ShareOption) => {
    option.onClick();
    // 移动端点击后收起
    if (isMobile) {
      setTimeout(() => setIsExpanded(false), 300);
    }
  }, [isMobile]);

  return (
    <>
      {/* 遮罩层 - 仅移动端展开时显示 */}
      <AnimatePresence>
        {isMobile && isExpanded && (
          <m.div
            className="fixed inset-0 z-40 bg-black/20"
            initial={{ opacity: 0 }}
            animate={{ opacity: 1 }}
            exit={{ opacity: 0 }}
            onClick={() => setIsExpanded(false)}
          />
        )}
      </AnimatePresence>

      {/* 悬浮球容器 */}
      <div
        className={cn(
          "fixed right-0 top-1/2 z-50 -translate-y-1/2",
          className
        )}
        onMouseEnter={handleMouseEnter}
        onMouseLeave={handleMouseLeave}
      >
        <div className="relative flex items-center">
          {/* 展开的分享选项 */}
          <AnimatePresence>
            {isExpanded && (
              <m.div
                className="absolute right-12 flex flex-col gap-2"
                initial={{ opacity: 0, x: 20, scale: 0.9 }}
                animate={{ opacity: 1, x: 0, scale: 1 }}
                exit={{ opacity: 0, x: 20, scale: 0.9 }}
                transition={{ type: "spring", damping: 25, stiffness: 300 }}
              >
                {/* 分享选项按钮 */}
                {options.map((option, index) => (
                  <m.button
                    key={option.key}
                    className="group flex items-center gap-2 rounded-full bg-white/95 py-2 pl-3 pr-4 text-brand-charcoal shadow-lg backdrop-blur-sm transition-all hover:scale-105 hover:bg-white active:scale-95"
                    onClick={() => handleOptionClick(option)}
                    initial={{ opacity: 0, x: 20 }}
                    animate={{ opacity: 1, x: 0 }}
                    transition={{ delay: index * 0.05 }}
                    whileHover={{ x: -4 }}
                  >
                    <span className="flex h-6 w-6 items-center justify-center">
                      {option.icon}
                    </span>
                    <span className="whitespace-nowrap text-sm font-medium">
                      {option.label}
                    </span>
                  </m.button>
                ))}

                {/* 保存图片按钮 */}
                {showSaveButton && onSaveImage && (
                  <m.button
                    className="flex items-center gap-2 rounded-full bg-white/95 py-2 pl-3 pr-4 text-brand-charcoal shadow-lg backdrop-blur-sm transition-all hover:scale-105 hover:bg-white active:scale-95 disabled:opacity-50"
                    onClick={onSaveImage}
                    disabled={isGeneratingImage}
                    initial={{ opacity: 0, x: 20 }}
                    animate={{ opacity: 1, x: 0 }}
                    transition={{ delay: options.length * 0.05 }}
                  >
                    <span className="flex h-6 w-6 items-center justify-center">
                      {isGeneratingImage ? (
                        <Loader2 className="h-5 w-5 animate-spin text-brand-gold" />
                      ) : (
                        <Download className="h-5 w-5 text-brand-gold" />
                      )}
                    </span>
                    <span className="whitespace-nowrap text-sm font-medium">
                      {isGeneratingImage ? "生成中..." : "保存图片"}
                    </span>
                  </m.button>
                )}
              </m.div>
            )}
          </AnimatePresence>

          {/* 主悬浮球按钮 */}
          <m.button
            className={cn(
              "flex h-12 w-12 items-center justify-center rounded-l-full bg-white shadow-xl transition-colors",
              "border border-r-0 border-brand-beige/50",
              "hover:bg-brand-champagne/30",
              isExpanded && "bg-brand-champagne/30"
            )}
            onClick={handleClick}
            whileHover={{ scale: 1.05 }}
            whileTap={{ scale: 0.95 }}
            aria-label="分享"
          >
            <AnimatePresence mode="wait">
              {copied ? (
                <m.div
                  key="check"
                  initial={{ scale: 0, rotate: -180 }}
                  animate={{ scale: 1, rotate: 0 }}
                  exit={{ scale: 0, rotate: 180 }}
                  transition={{ type: "spring", damping: 15 }}
                >
                  <Check className="h-5 w-5 text-green-500" />
                </m.div>
              ) : (
                <m.div
                  key="share"
                  initial={{ scale: 0 }}
                  animate={{ scale: 1 }}
                  exit={{ scale: 0 }}
                >
                  <Share2
                    className={cn(
                      "h-5 w-5 transition-colors",
                      isExpanded ? "text-brand-gold" : "text-brand-charcoal/70"
                    )}
                  />
                </m.div>
              )}
            </AnimatePresence>
          </m.button>
        </div>
      </div>
    </>
  );
}

