-- Consent versioning: distinguish material changes from ordinary edits.
ALTER TABLE "LegalDocumentVersion"
    ADD COLUMN "requiresReconsent" BOOLEAN NOT NULL DEFAULT false;

ALTER TABLE "PrivacyConsent"
    ADD COLUMN "documentVersion" INTEGER;

ALTER TABLE "ConsentEvent"
    ADD COLUMN "documentVersion" INTEGER;

CREATE INDEX "LegalDocumentVersion_documentId_requiresReconsent_version_idx"
    ON "LegalDocumentVersion"("documentId", "requiresReconsent", "version");

-- privacy v2 added the three-year evidence-retention clause, so it is material.
UPDATE "LegalDocumentVersion" AS v
SET "requiresReconsent" = true
FROM "LegalDocument" AS d
WHERE v."documentId" = d.id
  AND d.slug = 'privacy'
  AND v.version = 2;

